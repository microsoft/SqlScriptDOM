CREATE OR ALTER FUNCTION dbo.fx
(@s NVARCHAR (MAX))
RETURNS NVARCHAR (MAX)
AS
BEGIN
    RETURN (AI_SUMMARIZE(@s DEFAULT N'Summary unavailable' ON ERROR));
END
