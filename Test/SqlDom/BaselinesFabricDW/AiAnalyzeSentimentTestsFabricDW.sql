CREATE OR ALTER FUNCTION dbo.fx
(@s NVARCHAR (MAX))
RETURNS NVARCHAR (MAX)
AS
BEGIN
    RETURN (AI_ANALYZE_SENTIMENT(@s DEFAULT N'Sentiment unavailable' ON ERROR));
END
